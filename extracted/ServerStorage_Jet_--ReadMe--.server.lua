This is a Planekit that was made 100% by TurboFusion

This Planekit is a predecessor to my Planekit V1, which was a total failure due to my lack of scripting knowledge back then

This Planekit is a new and improved Planekit that was built 100% by me. It has new features, including the ability to lock
onto objects, the ability to be teleported to the plane seat when you regen the plane, and the ability to gradually lower
the altitude when you're at a low speed, so you can land on the runway smoothly

This Planekit has Missiles(can be guided), Bombs(can be guided), Flares, Guns, and Rockets

You can put the weapon's in the Weapons folder. Just make sure they're named according to what type of weapon they are

Make sure the dots on the weaponspawns are facing forward, or the projectiles that are fired from that spawn will go in random
directions

Make "EnterOnSpawn" false if you don't want to the person that pressed the regen button to be transported to plane seat the moment
the plane regenerates

HOW TO USE THIS PLANE:

1) Take any plane from the free models or build one

2) Take the Landing Gear from that plane and put it in the "Gear" Folder. (Plane > MainParts > Gear)

3) If you want the plane to have weapons, move the weapons in the weapon folders to where you want them to be on the plane. Make sure
   the dots on the weaponspawns are facing forward

4) Move the engine in the MainParts folder to anywhere on the plane, and make sure it is facing forward. You can resize it too

5) Move the seat to anywhere on the plane and make sure it is facing forward. You can resize it too

6) Take any remaining bricks and put it into the Bodykit folder

7) Go to the Customize Folder and read the "--ReadMe--"

That's pretty much it! It's that simple!

