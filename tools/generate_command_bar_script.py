#!/usr/bin/env python3
"""
Generates dist/InjectBoothScripts.lua: a single, self-contained Lua script
meant to be pasted into Roblox Studio's Command Bar (View tab -> Command
Bar). It operates directly on your existing "Rate My Avatar Booth" model
inside Studio -- no .rbxm import needed at all, which sidesteps whatever
was making Studio report the file as corrupted.

Run this generator whenever booth-kit/BoothServer.lua or
booth-kit/BoothClientUI.lua change, to keep dist/InjectBoothScripts.lua in
sync:

    python3 tools/generate_command_bar_script.py
"""
import os

HERE = os.path.dirname(__file__)
KIT_DIR = os.path.join(HERE, "..", "booth-kit")
DIST_DIR = os.path.join(HERE, "..", "dist")


def read_source(filename):
    with open(os.path.join(KIT_DIR, filename), "r", encoding="utf-8") as f:
        return f.read()


def lua_long_string(text):
    """Wrap text in a Lua long-bracket string literal, picking a bracket
    level that can't collide with any ']=*]' sequence already in the text."""
    level = 0
    while True:
        closer = "]" + ("=" * level) + "]"
        if closer not in text:
            break
        level += 1
    opener = "[" + ("=" * level) + "["
    closer = "]" + ("=" * level) + "]"
    # Lua strips a single leading newline right after the opening long
    # bracket, so a leading "\n" here is harmless/expected.
    return opener + "\n" + text + closer


TEMPLATE = '''-- InjectBoothScripts.lua
-- Generated by tools/generate_command_bar_script.py -- do not hand-edit;
-- edit booth-kit/BoothServer.lua / BoothClientUI.lua and regenerate.
--
-- HOW TO RUN THIS:
--   1. In Roblox Studio, select your "Booth" model in the Explorer
--      (the one your "Rate My Avatar Booth" model lives in / as).
--      If you don't select anything, this script will search the
--      whole game for a Model named "Booth" instead.
--   2. Open the Command Bar: View tab -> Command Bar.
--   3. Paste this entire script in and press Enter.
--   4. Read the Output window -- it prints exactly what it removed
--      and what it added.
--
-- WHAT THIS DOES:
--   1. Finds your booth Model.
--   2. Detects and deletes a known hidden backdoor: a disguised
--      Humanoid/HumanoidController/HumanoidDescription/
--      HumanoidRigDescription chain (normally wrapped in a StyleSheet
--      named "Extra") whose leaf Script does
--      require(script:WaitForChild("Pose", 4).Value) -- i.e. loads and
--      runs a remote ModuleScript by numeric asset id, live, forever,
--      in your published game. A companion Script self-destructs that
--      whole branch only when game.JobId == "" (Studio playtesting),
--      hiding it specifically when you test locally.
--   3. Adds a ProximityPrompt to the "Tabletop" part, a Remotes folder
--      (RequestClaim / RequestSaveBooth RemoteEvents), a State folder
--      (OwnerUserId / CustomTextValue / CustomImageIdValue), and the
--      two booth Scripts (BoothServer, BoothClientUI), wired to your
--      model's existing Banner -> SurfaceGui -> Frame ->
--      Description/Icon layout.
--
-- Safe to run more than once: it won't create duplicate instances or
-- re-add anything it already added.

local Selection = game:GetService("Selection")

local function findBoothRoot()
	local selected = Selection:Get()
	if selected[1] then
		return selected[1]
	end

	for _, container in ipairs({{ workspace, game:GetService("ServerStorage"), game:GetService("ReplicatedStorage") }}) do
		local direct = container:FindFirstChild("Booth", true)
		if direct then
			return direct
		end
	end

	return nil
end

local root = findBoothRoot()
if not root then
	error("Could not find your booth model. Select it in the Explorer first, then run this again.", 0)
end

print(("[InjectBoothScripts] Operating on: %s (%s)"):format(root:GetFullName(), root.ClassName))

-- ============================================================
-- STEP 1: Remove the hidden backdoor
-- ============================================================

local removedCount = 0

local function destroyWithReport(instance)
	print(("[InjectBoothScripts] Removing malicious instance: %s (%s)"):format(instance:GetFullName(), instance.ClassName))
	instance:Destroy()
	removedCount = removedCount + 1
end

-- Primary detection: any StyleSheet that contains a Humanoid descendant is
-- not a legitimate use of StyleSheet -- that combination only exists here
-- because of the disguised backdoor chain.
for _, inst in ipairs(root:GetDescendants()) do
	if inst:IsA("StyleSheet") then
		local hasHumanoidInside = false
		for _, descendant in ipairs(inst:GetDescendants()) do
			if descendant:IsA("Humanoid") then
				hasHumanoidInside = true
				break
			end
		end
		if hasHumanoidInside then
			destroyWithReport(inst)
		end
	end
end

-- Defense in depth: independently sweep for the exact malicious Script
-- signatures, in case they were relocated outside a StyleSheet wrapper.
for _, inst in ipairs(root:GetDescendants()) do
	if (inst:IsA("Script") or inst:IsA("LocalScript") or inst:IsA("ModuleScript")) and inst.Parent then
		local ok, source = pcall(function()
			return inst.Source
		end)
		if ok and type(source) == "string" then
			local looksLikeRemoteRequireBackdoor = source:find('WaitForChild("Pose"', 1, true) ~= nil
			local looksLikeSelfDestructor = source:find('JobId == ""', 1, true) ~= nil
			if looksLikeRemoteRequireBackdoor or looksLikeSelfDestructor then
				destroyWithReport(inst)
			end
		end
	end
end

if removedCount == 0 then
	print("[InjectBoothScripts] No backdoor instances found (already clean, or none present).")
else
	print(("[InjectBoothScripts] Removed %d malicious instance(s)."):format(removedCount))
end

-- ============================================================
-- STEP 2: Locate the parts/GUI this booth kit wires up to
-- ============================================================

local tabletop = root:FindFirstChild("Tabletop", true)
local banner = root:FindFirstChild("Banner", true)

if not tabletop then
	error('Could not find a part named "Tabletop" under ' .. root:GetFullName() ..
		". Rename your interaction part to \\"Tabletop\\" or edit this script's part names.", 0)
end

if not banner then
	error('Could not find a part named "Banner" under ' .. root:GetFullName() ..
		". Rename your sign part to \\"Banner\\" or edit this script's part names.", 0)
end

local surfaceGui = banner:FindFirstChildWhichIsA("SurfaceGui", true)
if not surfaceGui then
	error("Could not find a SurfaceGui under " .. banner:GetFullName() .. ".", 0)
end

local frame = surfaceGui:FindFirstChildWhichIsA("Frame", true)
if not frame then
	error("Could not find a Frame under " .. surfaceGui:GetFullName() .. ".", 0)
end

local description = frame:FindFirstChild("Description")
local icon = frame:FindFirstChild("Icon")

if not description then
	error('Could not find a TextLabel named "Description" under ' .. frame:GetFullName() .. ".", 0)
end

if not icon then
	error('Could not find an ImageLabel named "Icon" under ' .. frame:GetFullName() .. ".", 0)
end

print("[InjectBoothScripts] Found Tabletop, Banner, and Description/Icon labels.")

-- ============================================================
-- STEP 3: Idempotently create the supporting instances
-- ============================================================

local function getOrCreate(className, name, parent, configure)
	local existing = parent:FindFirstChild(name)
	if existing and existing.ClassName == className then
		if configure then
			configure(existing)
		end
		return existing, false
	end
	if existing then
		existing:Destroy()
	end
	local inst = Instance.new(className)
	inst.Name = name
	if configure then
		configure(inst)
	end
	inst.Parent = parent
	return inst, true
end

local prompt, promptCreated = getOrCreate("ProximityPrompt", "ProximityPrompt", tabletop, function(p)
	p.ActionText = "Claim Booth"
	p.ObjectText = "Unclaimed Booth"
	p.HoldDuration = 0.5
	p.MaxActivationDistance = 10
	p.RequiresLineOfSight = false
end)

local remotes = getOrCreate("Folder", "Remotes", root)
local requestClaim = getOrCreate("RemoteEvent", "RequestClaim", remotes)
local requestSaveBooth = getOrCreate("RemoteEvent", "RequestSaveBooth", remotes)

local state = getOrCreate("Folder", "State", root)
local ownerUserId = getOrCreate("IntValue", "OwnerUserId", state, function(v)
	if v.Value == nil then
		v.Value = 0
	end
end)
local customTextValue = getOrCreate("StringValue", "CustomTextValue", state)
local customImageIdValue = getOrCreate("StringValue", "CustomImageIdValue", state)

print(("[InjectBoothScripts] ProximityPrompt %s."):format(promptCreated and "created" or "already present (updated)"))
print("[InjectBoothScripts] Remotes and State ensured.")

-- ============================================================
-- STEP 4: Create/replace the two booth Scripts
-- ============================================================

local BOOTH_SERVER_SOURCE = {server_source}

local BOOTH_CLIENT_SOURCE = {client_source}

local function setScript(name, source, runContext, parent)
	local existing = parent:FindFirstChild(name)
	if existing and not existing:IsA("Script") then
		existing:Destroy()
		existing = nil
	end
	local scr = existing or Instance.new("Script")
	scr.Name = name
	scr.Source = source
	scr.RunContext = runContext
	scr.Disabled = false
	scr.Parent = parent
	return scr
end

setScript("BoothServer", BOOTH_SERVER_SOURCE, Enum.RunContext.Server, root)
setScript("BoothClientUI", BOOTH_CLIENT_SOURCE, Enum.RunContext.Client, root)

print("[InjectBoothScripts] BoothServer and BoothClientUI scripts installed.")
print("[InjectBoothScripts] Done! Your booth is ready -- interact with the Tabletop's prompt in-game to try it.")
'''


def main():
    server_source = read_source("BoothServer.lua")
    client_source = read_source("BoothClientUI.lua")

    output = TEMPLATE.format(
        server_source=lua_long_string(server_source),
        client_source=lua_long_string(client_source),
    )

    os.makedirs(DIST_DIR, exist_ok=True)
    out_path = os.path.join(DIST_DIR, "InjectBoothScripts.lua")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(output)

    print(f"Wrote {out_path} ({len(output)} bytes)")


if __name__ == "__main__":
    main()
